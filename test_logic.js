const fs=require('fs'), vm=require('vm'), assert=require('assert');
const html=fs.readFileSync(__dirname+'/index.html','utf8');
const script=html.match(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/i)[1];
const parseStart=script.indexOf(' parse(t){'); const parseEnd=script.indexOf('\n dt(d,t)',parseStart);
assert(parseStart>=0&&parseEnd>parseStart,'CSV parser exists');
let parseMethod=script.slice(parseStart,parseEnd).trim().replace(/^parse\(t\)/,'function parse(t)');
parseMethod=parseMethod.replace(/,$/,'');
const parseFn=new Function(`return (${parseMethod})`)();
const rows=parseFn('Date,HomeTeam,AwayTeam,Referee\r\n01/08/2026,"A, United",B,"Ref, One"\r\n02/08/2026,C,D,Ref Two');
assert.equal(rows.length,2);assert.equal(rows[0].HomeTeam,'A, United');assert.equal(rows[0].Referee,'Ref, One');
const bStart=script.indexOf('function btRun('), bEnd=script.indexOf('\nfunction vB()',bStart);
assert(bStart>=0&&bEnd>bStart,'Backtest function exists');
const bt=script.slice(bStart,bEnd);
const dt=(d,t)=>{const[a,b,c]=d.split('/');return new Date(+c,+b-1,+a)};
const emStart=script.indexOf(' estimateMarket(rows,'), emEnd=script.indexOf(',\n async statsFor',emStart);
assert(emStart>=0&&emEnd>emStart,'opponent-adjusted estimator exists');
let em=script.slice(emStart,emEnd).trim();
const estimateMarket=new Function('Csv',`return ({${em}}).estimateMarket` )({dt});
const Csv={dt,estimateMarket};
const ctx={Map,Math,Number,Date,Csv,pOver:(l,mu)=>{let s=0,t=Math.exp(-mu);for(let i=0;i<=Math.floor(l);i++){s+=t;t*=mu/(i+1)}return 1-s}};
vm.createContext(ctx);vm.runInContext(`const BT_COLS=${script.match(/const BT_COLS=\{[\s\S]*?\};/)[0].replace(/^const BT_COLS=/,'')};\n${bt}`,ctx);
const sample=[];for(let i=1;i<=10;i++)sample.push({Date:`${String(i).padStart(2,'0')}/08/2026`,Time:'15:00',HomeTeam:i%2?'A':'B',AwayTeam:i%2?'B':'A',FTHG:'1',FTAG:'0',HC:String(i%3+3),AC:String(i%2+2),HS:String(i%5+10),AS:String(i%4+9),HF:String(i%6+8),AF:String(i%5+9),HY:'1',AY:'2'});
const result=ctx.btRun(sample,'co',8.5);assert(result.n>0,'Backtest creates predictions after minimum history');assert(result.items.every(x=>x.p>=0&&x.p<=1),'Probabilities bounded');assert(result.brier>=0&&result.brier<=1,'Brier score bounded');
console.log('PASS: quoted CSV parser, chronological backtest, probability bounds, Brier score. Predictions:',result.n);
